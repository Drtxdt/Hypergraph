import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage();
const html=await fs.readFile('.local/demo/public/2026/10/28/welcome/index.html','utf8');
const requests=[],errors=[];
page.on('request',r=>requests.push(r.url()));
page.on('pageerror',e=>errors.push(e.message));
await page.route('https://giscus.app/**',r=>r.fulfill({contentType:'text/javascript',body:''}));
await page.route('https://utteranc.es/**',r=>r.fulfill({contentType:'text/javascript',body:''}));
const config={enable:true,lazy:true,provider:'giscus',repo:'test/repo',repo_id:'id',category_id:'id',options:{},secondary:{enable:true,provider:'utterances',repo:'test/repo',options:{}}};
await page.route('**/options/',r=>r.fulfill({contentType:'text/html',body:html.replace(/(<script type="application\/json" data-comment-config>)[\s\S]*?(<\/script>)/,'$1'+JSON.stringify(config)+'$2').replace('data-comments','style="margin-top:4000px" data-comments')}));
await page.goto('http://127.0.0.1:4174/options/',{waitUntil:'networkidle'});
assert.ok(!requests.some(r=>r.includes('giscus.app')),'Lazy comments must not contact provider before entering view');
await page.locator('[data-comments]').scrollIntoViewIfNeeded();
await page.waitForFunction(()=>!!document.querySelector('[data-comment-body] script[src*="giscus"]'));
await page.getByLabel('评论服务 / Comment service').selectOption('secondary');
await page.waitForSelector('.comment-frame');
assert.equal(await page.locator('[data-comment-body] script[src*="giscus"]').count(),0);
await page.getByLabel('评论服务 / Comment service').selectOption('primary');
await page.waitForFunction(()=>!!document.querySelector('[data-comment-body] script[src*="giscus"]'));
assert.equal(await page.locator('.comment-frame').count(),0);
await page.goto('http://127.0.0.1:4173/');
await page.locator('[data-search]').click();
await page.locator('#search-input').fill('a');
await page.locator('[data-results] li').first().waitFor();
const first=await page.locator('[data-results] li').first().textContent();
assert.equal(await page.locator('[data-results] li').count(),10);
await page.getByRole('button',{name:'Next →',exact:true}).click();
await page.waitForFunction(first=>document.querySelector('[data-results] li')?.textContent!==first,first);
await page.getByRole('button',{name:'← Previous',exact:true}).click();
await page.waitForFunction(first=>document.querySelector('[data-results] li')?.textContent===first,first);
await page.locator('#search-input').fill('');
assert.equal(await page.getByRole('button',{name:'Next →',exact:true}).isVisible(),false);
assert.deepEqual(errors,[]);
await browser.close();
console.log('Lazy/dual comment lifecycle and search pagination passed.');
