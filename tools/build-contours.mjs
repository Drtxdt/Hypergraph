import fs from "node:fs/promises";
import { createHash } from "node:crypto";
import { gzipSync } from "node:zlib";
// Original deterministic height field; marching squares with an asymptotic decider.
const field = (x, y) =>
  1.8 * Math.exp(-((x - 0.67) ** 2 / 0.045 + (y - 0.48) ** 2 / 0.14)) +
  0.95 * Math.exp(-((x - 0.21) ** 2 / 0.025 + (y - 0.76) ** 2 / 0.04)) -
  0.7 * Math.exp(-((x - 0.49) ** 2 / 0.018 + (y - 0.23) ** 2 / 0.025)) +
  0.16 * Math.sin(17 * x + 3 * y) * Math.cos(13 * y - 2 * x);
const terrain = [];
const W = 1200,
  H = 600,
  nx = 100,
  ny = 50;
for (let level = -0.5, index = 0; level < 2; level += 0.105, index++) {
  const segments = [];
  for (let y = 0; y < ny; y++)
    for (let x = 0; x < nx; x++) {
      const p = [
          [x, y],
          [x + 1, y],
          [x + 1, y + 1],
          [x, y + 1],
        ],
        v = p.map(([a, b]) => field(a / nx, b / ny) - level),
        edges = [];
      for (let e = 0; e < 4; e++) {
        const j = (e + 1) % 4;
        if (v[e] > 0 !== v[j] > 0) {
          const t = v[e] / (v[e] - v[j]);
          edges.push([
            e,
            [
              ((p[e][0] + t * (p[j][0] - p[e][0])) * W) / nx,
              ((p[e][1] + t * (p[j][1] - p[e][1])) * H) / ny,
            ],
          ]);
        }
      }
      const add = (a, b) =>
        segments.push(
          `M${edges[a][1].map((z) => z.toFixed(1)).join(",")}L${edges[b][1].map((z) => z.toFixed(1)).join(",")}`,
        );
      if (edges.length === 2) add(0, 1);
      if (edges.length === 4) {
        if (v[0] * v[2] - v[1] * v[3] > 0) {
          add(0, 1);
          add(2, 3);
        } else {
          add(0, 3);
          add(1, 2);
        }
      }
    }
  terrain.push(
    `<path d="${segments.join("")}" stroke-width="${index % 5 === 0 ? 1.8 : 0.8}"/>`,
  );
}
const flow = Array.from(
  { length: 30 },
  (_, i) =>
    `<path d="M-20 ${i * 22 - 70}C230 ${i * 18 - 120} 400 ${i * 13 + 360} 690 ${i * 18 + 140}S1020 ${i * 24 - 80} 1220 ${i * 22 + 60}" stroke-width="${i % 5 === 0 ? 1.7 : 0.8}"/>`,
);
const svg = (paths) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 600" fill="none" stroke="#72777a">${paths.join("")}</svg>`;
const points = [];
// Three offset folded planes, with a clear central negative space.
for (let layer = 0; layer < 3; layer++)
  for (let y = 0; y < 40; y++)
    for (let x = 0; x < 40; x++) {
      if (x > 11 && x < 28 && y > 11 && y < 28) continue;
      if ((x + y) % 2) continue;
      points.push([
        600 + (x - y) * 6 + layer * 26,
        120 + (x + y) * 3 + layer * 65,
      ]);
    }
await fs.mkdir("src/generated", { recursive: true });
await fs.writeFile(
  "src/generated/artwork-points.ts",
  "// Generated by tools/build-contours.mjs; original geometry.\nexport default " +
    JSON.stringify(points.filter((_, i) => i % 2 === 0)) +
    ";\n",
);
const artwork = svg(
  points.map(
    ([x, y]) =>
      `<circle cx="${x}" cy="${y}" r="2" fill="#74797a" stroke="none"/>`,
  ),
);
const manifest = {};
let total = 0;
await fs.mkdir("source/assets", { recursive: true });
for (const [key, body] of Object.entries({
  terrain: svg(terrain),
  flow: svg(flow),
  artwork,
})) {
  const name = `${key}-${createHash("sha256").update(body).digest("hex").slice(0, 12)}.svg`;
  await fs.writeFile("source/assets/" + name, body);
  await fs.writeFile("source/assets/" + name + ".gz", gzipSync(body,{level:9}));
  manifest[key] = name;
  total += gzipSync(body).length;
}
if (total > 30720) throw Error(`Contour budget exceeded: ${total}`);
await fs.writeFile(
  "source/assets/contours.json",
  JSON.stringify({ ...manifest, gzip: total }),
);
console.log(`Original contour assets: ${total} gzip bytes`);
